# Faster minor-key boss score: low ostinato, drums, strings and a rising alarm motif.
beat=60/138
length=16*4*beat
boss_music=array("f",[0.0])*round(length*RATE)
progression=[[45,48,52],[41,45,48],[43,46,50],[40,44,47]]
def drum(buf,start,gain=0.25):
    offset=int(start*RATE)
    for i in range(min(int(RATE*0.22),len(buf)-offset)):
        t=i/RATE
        value=math.sin(2*math.pi*(70*t-75*t*t))*math.exp(-t*18)
        buf[offset+i]+=gain*value
for bar in range(16):
    start=bar*4*beat; chord=progression[bar%4]
    for pitch in chord: note(boss_music,start,beat*3.8,pitch+12,0.045,"pad")
    for step in range(8):
        note(boss_music,start+step*beat/2,beat*0.45,chord[step%3]-12,0.17)
        note(boss_music,start+step*beat/2,beat*0.35,chord[(step+1)%3]+12,0.075)
    for step in [0,1.5,2,3.5]: drum(boss_music,start+step*beat)
    for step,pitch in enumerate([chord[0]+24,chord[0]+25,chord[2]+24,chord[0]+24]):
        note(boss_music,start+step*beat,beat*0.65,pitch,0.08)
for i in range(int(RATE*0.015)):
    boss_music[i]*=i/(RATE*0.015); boss_music[-1-i]*=i/(RATE*0.015)
write("boss_theme",boss_music)
# Each elite has an audible attack identity and a stronger skill accent.
styles=["roar","claw","fang","shadow","wind","spirit","ice","sun","lightning","nature","abyss","heaven","hell"]
pitches=[38,50,45,55,69,81,88,76,90,79,33,84,36]
for idx,(style,pitch) in enumerate(zip(styles,pitches)):
    for is_skill in [False]:
        duration=0.58 if is_skill else 0.22
        buf=array("f",[0.0])*int(RATE*(duration+0.18))
        intervals=[0,7,12] if is_skill else [0,7]
        for n,interval in enumerate(intervals):
            note(buf,n*0.055,duration-n*0.055,pitch+interval,0.24 if is_skill else 0.18)
        if style in ["roar","claw","fang","abyss","hell"]: drum(buf,0,0.35)
        if style in ["claw","wind","lightning","ice"]:
            for i in range(int(RATE*duration)):
                t=i/RATE
                # Deterministic inharmonic noise-like transient, no combat RNG.
                hiss=math.sin(2*math.pi*(1800*t+900*t*t))*math.sin(2*math.pi*2713*t)
                buf[i]+=0.16*hiss*math.exp(-t*13)
        write(("skill_" if is_skill else "attack_")+style,buf)
