"""Original procedural fantasy score and UI/combat sounds; no third-party samples."""
from pathlib import Path
from array import array
import math, wave, sys
RATE=22050
OUT=Path(__file__).resolve().parents[1]/"game/audio"
OUT.mkdir(parents=True,exist_ok=True)
def hz(note): return 440.0*2.0**((note-69)/12.0)
def note(buf,start,duration,midi,gain=0.1,tone="harp"):
    first=int(start*RATE)
    count=min(int(duration*RATE),len(buf)-first)
    f=hz(midi)
    for i in range(max(0,count)):
        t=i/RATE
        attack=min(1.0,t/0.012)
        release=min(1.0,(duration-t)/0.08)
        phase=2*math.pi*f*t
        if tone=="pad":
            value=(math.sin(phase)+0.25*math.sin(phase*2)+0.12*math.sin(phase*3))*attack*release
        else:
            value=(math.sin(phase)+0.32*math.sin(phase*2)+0.1*math.sin(phase*3))*math.exp(-t*5.5)*attack*release
        buf[first+i]+=gain*value
def write(name,buf):
    data=array("h",(round(max(-0.95,min(0.95,float(x)))*32767) for x in buf))
    if sys.byteorder!="little": data.byteswap()
    with wave.open(str(OUT/(name+".wav")),"wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(data.tobytes())
beat=60/90
length=16*4*beat
music=array("f",[0.0])*round(length*RATE)
chords=[[60,64,67],[57,60,64],[53,57,60],[55,59,62]]
melody=[79,76,74,72,76,79,81,79,77,76,74,72,74,76,71,72]
for bar in range(16):
    start=bar*4*beat
    chord=chords[bar%4]
    for pitch in chord: note(music,start,4*beat,pitch-12,0.035,"pad")
    for step in range(8): note(music,start+step*beat/2,beat*0.8,chord[step%3]+12,0.08)
    note(music,start+beat,beat*1.7,melody[bar],0.10)
# Short edge fade prevents a click at the loop boundary.
for i in range(int(RATE*0.02)):
    music[i]*=i/(RATE*0.02)
    music[-1-i]*=i/(RATE*0.02)
write("sky_theme",music)
patterns={
"ui":([84],0.10),"summon":([72,76,79],0.34),"attack":([57],0.10),
"magic":([84,91],0.18),"craft":([72,76,79,84],0.8),
"coin":([88,93],0.20),"wave":([60,67,72],0.65),
"boss":([43,43,50],0.9),"victory":([72,76,79,84,88],1.5),
"defeat":([60,58,55,48],1.3)}
for name,(pitches,duration) in patterns.items():
    buf=array("f",[0.0])*int(RATE*(duration+0.2))
    for i,pitch in enumerate(pitches):
        note(buf,i*duration/len(pitches),duration/len(pitches)+0.18,pitch,0.3)
    write(name,buf)
(OUT/"README.txt").write_text("Original procedural music and sound effects composed for MeongRandy. Generated by tools/generate_audio.py. No external recordings or samples.\n",encoding="utf-8")
print("Generated original music and 10 effects")
